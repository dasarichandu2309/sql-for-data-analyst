);

INSERT INTO EMP2 VALUES
(1,'A',24),(2,'B',25),(3,'C',26);

INSERT INTO SALARY2 VALUES
(101,1,50000),(102,2,55000);

-- LEFT JOIN
SELECT E.EMPID,E.FNAME,S.AMOUNT
FROM EMP2 E 
LEFT JOIN SALARY2 S
ON E.EMPID = S.EMPID;

-- RIGHT JOIN
